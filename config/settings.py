# -----------------------------------------------------------------------------
# Automated Testing Configuration & Safety Guards (PostgreSQL-First)
# -----------------------------------------------------------------------------
# By default, 'python manage.py test' executes against an isolated PostgreSQL database (healthcare_test_db).
# Fast in-memory SQLite is optional and requires explicit opt-in by setting USE_SQLITE_TEST_DB=True.
import sys

IS_TESTING = 'test' in sys.argv or any('test' in arg for arg in sys.argv)
USE_SQLITE_TEST_DB = env.bool('USE_SQLITE_TEST_DB', default=False)

if IS_TESTING:
    if USE_SQLITE_TEST_DB:
        # Explicit opt-in for fast in-memory SQLite unit testing
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': ':memory:',
            }
        }
    else:
        # Default: Enforce PostgreSQL test database with strict safety guards
        resolved_test_db = DATABASES['default'].get('TEST', {}).get('NAME')

        # Guard 1: Dedicated test database name required
        if not resolved_test_db:
            raise ImproperlyConfigured(
                "PostgreSQL testing is default, but no test database name is configured in DATABASES['default']['TEST']['NAME']."
            )

        # Guard 2: Must never target development database
        if resolved_test_db == DB_NAME:
            raise ImproperlyConfigured(
                f"SAFETY GUARD VIOLATION: Test database '{resolved_test_db}' matches development database '{DB_NAME}'. "
                "Tests must never run against the development database."
            )

        # Guard 3: Must never target protected databases (postgres, template1, sis, etc.)
        protected_dbs = {'postgres', 'template0', 'template1', 'sis', 'sis_db'}
        if resolved_test_db.lower() in protected_dbs:
            raise ImproperlyConfigured(
                f"SAFETY GUARD VIOLATION: Test database '{resolved_test_db}' is a protected system or company database name."
            )

        # Guard 4: Must use the dedicated test database name 'healthcare_test_db'
        if resolved_test_db != 'healthcare_test_db':
            raise ImproperlyConfigured(
                f"SAFETY GUARD VIOLATION: PostgreSQL tests must only target 'healthcare_test_db', got '{resolved_test_db}'."
            )

        # Guard 5: Must use dedicated user (not superuser 'postgres')
        if DB_USER.lower() == 'postgres':
            raise ImproperlyConfigured(
                "SAFETY GUARD VIOLATION: PostgreSQL tests must run using the dedicated 'healthcare_admin' user, not superuser 'postgres'."
            )

        # Guard 6: Ensure engine is strictly PostgreSQL (do not silently fall back to SQLite)
        if DATABASES['default']['ENGINE'] != 'django.db.backends.postgresql':
            raise ImproperlyConfigured(
                f"PostgreSQL testing required by policy, but database engine is '{DATABASES['default']['ENGINE']}'."
            )

